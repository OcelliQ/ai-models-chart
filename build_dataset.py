#!/usr/bin/env python3
"""Join live OpenRouter pricing/volume with curated model_overrides.csv.

``openrouter_live.csv`` is regenerated by ``refresh_prices.py``. Rows with
``inclusion=benchmark_cohort`` or ``volume_status=not_observed`` are not usage
ranks: their ``avg_monthly_tokens`` value of 0 is a sentinel. ``price_status``
is ``live``, ``override`` (instructor price), or ``stale`` (delisted, last
price kept).
``external`` prices are manually sourced from a provider outside OpenRouter;
``volume_status=nominal`` marks a usage placeholder, not a measurement.

``model_overrides.csv`` holds AAII, open weights, country, and display name.
Existing scores are preserved by the refresh; new rows are appended only for
models that entered the live table.

Produces ``models.csv`` plus ``price_per_task_100k_in_8k_out``.
"""

import csv
from pathlib import Path

HERE = Path(__file__).parent
LIVE = HERE / "openrouter_live.csv"
OVERRIDES = HERE / "model_overrides.csv"
OUT = HERE / "models.csv"

TASK_INPUT_TOKENS = 100_000
TASK_OUTPUT_TOKENS = 8_000

FIELDS = [
    "canonical_id",
    "display_name",
    "price_per_m_input",
    "price_per_m_output",
    "price_per_task_100k_in_8k_out",
    "aaii",
    "open_weights",
    "country",
    "avg_monthly_tokens",
    "context_length",
    "notes",
    "price_status",
    "inclusion",
    "volume_status",
    "pinned",
    "openrouter_id",
    "volume_rank",
    "observed_days",
]


def main():
    live = {row["canonical_id"]: row for row in csv.DictReader(LIVE.open())}
    overrides = {row["canonical_id"]: row for row in csv.DictReader(OVERRIDES.open())}

    only_live = set(live) - set(overrides)
    only_overrides = set(overrides) - set(live)
    if only_live:
        preview = ", ".join(sorted(only_live)[:10])
        suffix = " ..." if len(only_live) > 10 else ""
        print(
            f"note: {len(only_live)} live models have no override row "
            f"(AAII/openness/country blank): {preview}{suffix}"
        )
    if only_overrides:
        preview = ", ".join(sorted(only_overrides)[:10])
        print(
            f"note: {len(only_overrides)} override rows are not in the live table "
            f"and are omitted from models.csv: {preview}"
        )

    out_rows = []
    for canonical_id, live_row in live.items():
        override = overrides.get(canonical_id, {})
        price_in = float(live_row["price_per_m_input"])
        price_out = float(live_row["price_per_m_output"])
        price_per_task = (
            price_in * TASK_INPUT_TOKENS + price_out * TASK_OUTPUT_TOKENS
        ) / 1_000_000
        out_rows.append(
            {
                "canonical_id": canonical_id,
                "display_name": override.get("display_name") or live_row["openrouter_name"],
                "price_per_m_input": live_row["price_per_m_input"],
                "price_per_m_output": live_row["price_per_m_output"],
                "price_per_task_100k_in_8k_out": round(price_per_task, 4),
                "aaii": override.get("aaii", ""),
                "open_weights": override.get("open_weights", ""),
                "country": override.get("country", ""),
                "avg_monthly_tokens": live_row["avg_monthly_tokens"],
                "context_length": live_row["context_length"],
                "notes": override.get("notes", ""),
                "price_status": live_row.get("price_status", ""),
                "inclusion": live_row.get("inclusion", ""),
                "volume_status": live_row.get("volume_status", ""),
                "pinned": live_row.get("pinned", ""),
                "openrouter_id": live_row.get("openrouter_id", ""),
                "volume_rank": live_row.get("volume_rank", ""),
                "observed_days": live_row.get("observed_days", ""),
            }
        )

    out_rows.sort(key=lambda row: -int(row["avg_monthly_tokens"] or 0))
    with OUT.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(out_rows)

    scored = sum(1 for row in out_rows if row["aaii"])
    ranked = sum(1 for row in out_rows if row["inclusion"] == "ranked")
    cohort = sum(1 for row in out_rows if row["inclusion"] == "benchmark_cohort")
    print(
        f"wrote {len(out_rows)} models to {OUT} ({scored} have an AAII score, "
        f"{ranked} ranked, {cohort} benchmark_cohort)"
    )


if __name__ == "__main__":
    main()
